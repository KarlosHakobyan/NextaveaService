/* --------------------------------------------------------------------------
   Language selection
   -------------------------------------------------------------------------- */

let active = null;

export function currentLang() {
    if (active) return active;
    const stored = readPref(KEYS.ADMIN_LANG);
    active = LANGS.some(l => l.id === stored) ? stored : DEFAULT_LANG;
    return active;
}

export function setLang(id) {
    if (!LANGS.some(l => l.id === id)) return;
    writePref(KEYS.ADMIN_LANG, id);
    active = id;
}

/** BCP 47 tag for Intl formatting, so dates and money follow the language. */
export function locale() {
    const found = LANGS.find(l => l.id === currentLang());
    return found ? found.locale : 'en-GB';
}

/* --------------------------------------------------------------------------
   Lookup
   -------------------------------------------------------------------------- */

function interpolate(text, vars) {
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (whole, name) =>
        Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole);
}

/**
 * Picks the plural form for `n`.
 * English and French have two forms; French treats 0 as singular.
 * Russian has three: 1, 2-4, and everything else, with the teens as
 * exceptions (11-14 take the third form).
 */
function pluralIndex(lang, n) {
    if (lang === 'ru') {
        const mod10 = n % 10;
        const mod100 = n % 100;
        if (mod10 === 1 && mod100 !== 11) return 0;
        if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 1;
        return 2;
    }
    if (lang === 'fr') return n > 1 ? 1 : 0;
    return n === 1 ? 0 : 1;
}

/**
 * @param {string} key
 * @param {object} [vars] values for {placeholders}; `n` also selects the
 *                        plural form when the entry is an array.
 */
export function t(key, vars) {
    const lang = currentLang();
    const table = STRINGS[lang] || STRINGS[DEFAULT_LANG];
    let entry = table[key];

    if (entry === undefined) entry = STRINGS[DEFAULT_LANG][key];
    // A missing key shows as the key itself, which is loud enough to notice
    // and specific enough to fix.
    if (entry === undefined) return key;

    if (Array.isArray(entry)) {
        const n = vars && typeof vars.n === 'number' ? vars.n : 0;
        entry = entry[pluralIndex(lang, n)] ?? entry[entry.length - 1];
    }

    return interpolate(entry, vars);
}

/* --------------------------------------------------------------------------
   Language switcher
   Changing language reloads the page: every screen builds its text once, at
   render time, and a reload is both simpler and more reliable than trying to
   re-translate a live DOM.
   -------------------------------------------------------------------------- */

export function createLangSelect(className) {
    const select = document.createElement('select');
    select.className = className;
    select.setAttribute('aria-label', t('shell.language'));
    select.innerHTML = LANGS.map(l =>
        `<option value="${l.id}"${l.id === currentLang() ? ' selected' : ''}>${l.name}</option>`
    ).join('');

    select.addEventListener('change', e => {
        setLang(e.target.value);
        window.location.reload();
    });

    return select;
}

/** Sets <html lang> so screen readers and hyphenation follow the console. */
export function applyDocumentLang() {
    document.documentElement.lang = currentLang();
}
