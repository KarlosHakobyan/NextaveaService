/* ==========================================================================
   Console translations: English, French, Russian.

   One flat key map per language. Every string the operator can read lives
   here, so a missing translation is a visible gap in one file rather than a
   sentence hidden in a page.

   Interpolation uses {name} placeholders. Russian needs three plural forms
   and French two, so counted strings are declared as arrays and resolved by
   plural() rather than by appending an "s".

   The chosen language is stored under its own preference key. It is separate
   from the public site's language on purpose: the site speaks seven, this
   console speaks three, and a visitor switching the site to Dutch should not
   change what the operator sees.
   ========================================================================== */

